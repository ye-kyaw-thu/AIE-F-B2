export function translate(text:string,locale:Locale):string {
  if(locale==="en")return text;
  const key=text.replace(/\s+/g," ").trim();
  const shipmentCount=key.match(/^(\d+) shipments?(?: · (.+))?$/);
  if(shipmentCount)return `${shipmentCount[1]} ခု${shipmentCount[2]?" · "+translate(shipmentCount[2],locale):""}`;
  const result=Object.prototype.hasOwnProperty.call(burmese,key)?burmese[key]:undefined;
  if(!result)return text;
  return (text.match(/^\s*/)?.[0]??"")+result+(text.match(/\s*$/)?.[0]??"");
}
